#!/usr/bin/env python3
"""Generate the SDK type definitions from ``schema.json``.

The SDK files in ``sdk/`` are the hand-copy target for AI pipelines, so they
must not drift away from the renderer schema. This script is the only writer:

    python3 scripts/gen_sdk.py            # rewrite both SDK files
    python3 scripts/gen_sdk.py --check    # exit 1 when the files are stale

``tests/sdk_parity.rs`` enforces the same thing during ``cargo test`` by
comparing the field and enum names, so a stale file fails CI even when Python
is not available.
"""

from __future__ import annotations

import json
import keyword
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema.json"
TS_OUT = ROOT / "sdk" / "typescript" / "rustren.d.ts"
PY_OUT = ROOT / "sdk" / "python" / "rustren_types.py"

# Contract-level names rather than layer/schema names.
RENAMES = {
    "BaseLayer": "BaseLayer",
    "Layer": "Layer",
    "ContainerLayer": "ContainerLayer",
    "RectLayer": "RectLayer",
    "CircleLayer": "CircleLayer",
    "TextLayer": "TextLayer",
    "SvgLayer": "SvgLayer",
    "ImageLayer": "ImageLayer",
    "VideoLayer": "VideoLayer",
    "WaveformLayer": "WaveformLayer",
    "LottieLayer": "LottieLayer",
    "ParticlesLayer": "ParticlesLayer",
    "Mesh3dLayer": "Mesh3dLayer",
    "IncludeLayer": "IncludeLayer",
    "Animation": "Animation",
    "LinearGradient": "LinearGradient",
    "Layout": "Layout",
    "Shadow": "Shadow",
    "TextSpan": "TextSpan",
    "SpringConfig": "SpringConfig",
    "Echo": "Echo",
    "HexColor": "HexColor",
}

# Open objects the schema leaves untyped; these keep a hand-written shape.
OPEN_OBJECTS = {
    ("TextLayer", "dynamic"): "DynamicText",
    ("IncludeLayer", "vars"): "Record<string, string>",
    ("IncludeLayer", "variables"): "Record<string, string>",
    # Top-level objects that do have a hand-named interface below.
    ("scene", "canvas"): "Canvas",
    ("scene", "profiles"): "Record<string, CompositionProfile>",
    ("scene", "audio"): "AudioTrack[]",
}

# Python counterpart of OPEN_OBJECTS. Kept separate because the spellings differ.
PY_OPEN_OBJECTS = {
    ("LinearGradient", "stops"): "list[GradientStop]",
    ("Animation", "keyframes"): "list[Keyframe]",
    ("scene", "canvas"): "Canvas",
    ("scene", "profiles"): "dict[str, CompositionProfile]",
    ("scene", "audio"): "list[AudioTrack]",
}

HEADER_TS = """// Generated by scripts/gen_sdk.py from schema.json. Do not edit by hand.
// Run `python3 scripts/gen_sdk.py` after changing the schema.
// Fields are optional unless marked required; defaults are in the doc comment.
"""

HEADER_PY = '''"""Generated by scripts/gen_sdk.py from schema.json. Do not edit by hand.

Run `python3 scripts/gen_sdk.py` after changing the schema.

TypedDict subclasses use ``total=False`` because most scene fields have defaults;
each class docstring lists the fields the renderer actually requires.
"""

from __future__ import annotations

from typing import Any, Literal, TypedDict, Union
'''


def load_schema():
    return json.loads(SCHEMA.read_text())


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def literal_union(values, sep: str = " | ") -> str:
    parts = []
    for value in values:
        if isinstance(value, bool):
            parts.append("true" if value else "false")
        elif isinstance(value, (int, float)):
            parts.append(str(value))
        else:
            parts.append(json.dumps(value))
    return sep.join(parts)


def is_union_of_literals(schema) -> bool:
    if "enum" not in schema:
        return False
    return all(
        isinstance(v, (str, int, float, bool)) for v in schema["enum"]
    )


# Array-of-object properties whose item schema is inline rather than a `$def`.
INLINE_ITEM_TYPES = {
    ("LinearGradient", "stops"): "GradientStop",
    ("Animation", "keyframes"): "Keyframe",
}


def ts_type(schema: dict, owner: str, key: str) -> str:
    override = OPEN_OBJECTS.get((owner, key))
    if override:
        return override
    if "type" in schema and schema["type"] == "array" and (owner, key) in INLINE_ITEM_TYPES:
        return INLINE_ITEM_TYPES[(owner, key)] + "[]"
    if "$ref" in schema:
        return ref_name(schema["$ref"])
    if "const" in schema:
        value = schema["const"]
        return "true" if value is True else "false" if value is False else json.dumps(value)
    if is_union_of_literals(schema):
        return literal_union(schema["enum"])
    if "oneOf" in schema:
        return " | ".join(ts_type(s, owner, key) for s in schema["oneOf"])
    kind = schema.get("type")
    if kind == "array":
        inner = ts_type(schema.get("items", {}), owner, key)
        if " | " in inner or inner.startswith("Record") or inner.endswith("[]") or inner == "Layer":
            if inner == "Layer":
                return "Layer[]"
            return f"({inner})[]"
        return f"{inner}[]"
    if kind == "object":
        # Intentionally open object without a matching $def (e.g. text outline).
        if "properties" in schema:
            return "Record<string, unknown>"
        return "Record<string, unknown>"
    if kind == "integer" or kind == "number":
        return "number"
    if kind == "boolean":
        return "boolean"
    return "string"


def py_str_literal(values) -> str:
    # Python's Literal needs commas, unlike the TypeScript union.
    return "Literal[" + literal_union(values, sep=", ") + "]"


def py_type(schema: dict, owner: str, key: str) -> str:
    override = PY_OPEN_OBJECTS.get((owner, key))
    if override:
        return override
    if "$ref" in schema:
        name = ref_name(schema["$ref"])
        if name == "HexColor":
            return "str"
        # `Layer` is a self-referential union: keep it a forward reference.
        return '"Layer"' if name == "Layer" else name
    if "const" in schema:
        value = schema["const"]
        if isinstance(value, str):
            return py_str_literal([value])
        return "bool" if isinstance(value, bool) else py_type(schema, owner, key)
    if is_union_of_literals(schema):
        return py_str_literal(schema["enum"])
    if "oneOf" in schema:
        return "Union[" + ", ".join(py_type(s, owner, key) for s in schema["oneOf"]) + "]"
    kind = schema.get("type")
    if kind == "array":
        return "list[" + py_type(schema.get("items", {}), owner, key) + "]"
    if kind == "object":
        if key in ("vars", "variables"):
            return "dict[str, str]"
        return "dict[str, Any]"
    if kind == "boolean":
        return "bool"
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    return "str"


PY_KEYWORDS = {"from", "global", "lambda", "class", "def", "import", "in", "is", "not", "or", "and"}


def py_field(key: str) -> str:
    """Field name as it appears in a class-body annotation."""
    return key + "_" if keyword.iskeyword(key) else key


def typed_dict(
    name: str,
    props: dict,
    owner: str,
    doc: str,
    indent: str = "",
    skip: set[str] | None = None,
) -> list[str]:
    """Emit a TypedDict, using the functional form when a field is a keyword.

    The functional form takes a plain dict, so a JSON key like `from` can be
    spelled exactly as the renderer expects instead of a lossy `from_` alias.
    """
    skip = skip or set()
    keys = [k for k in props if k not in skip]
    if any(keyword.iskeyword(k) for k in keys):
        entries = []
        for key in keys:
            entries.append(f'        "{key}": {py_type(props[key], owner, key)},')
        return [
            f'{indent}{name} = TypedDict(',
            f'{indent}    "{name}",',
            f'{indent}    {{',
            *entries,
            f'{indent}    }},',
            f'{indent}    total=False,',
            f'{indent})',
            f'{indent}"""',
            f'{indent}{doc}',
            f'{indent}"""',
        ]
    lines = [f"{indent}class {name}(TypedDict, total=False):", f'{indent}    """{doc}"""']
    for key in keys:
        lines.append(f"{indent}    {key}: {py_type(props[key], owner, key)}")
    return lines


def doc_line(schema: dict) -> str:
    bits = []
    if "description" in schema:
        bits.append(schema["description"].strip().rstrip("."))
    if "default" in schema:
        bits.append("default: " + json.dumps(schema["default"]))
    if "minimum" in schema:
        bits.append(f"min: {schema['minimum']}")
    if "maximum" in schema:
        bits.append(f"max: {schema['maximum']}")
    if "minLength" in schema:
        bits.append(f"minLength: {schema['minLength']}")
    return "; ".join(bits)


def layer_defs(defs: dict) -> list[str]:
    return [
        name
        for name in defs
        if name.endswith("Layer") and name not in ("IncludeLayer", "Layer", "BaseLayer")
        and "properties" in defs[name]
    ]


def compute_base_fields(defs: dict, names: list[str]) -> list[str]:
    sets = [set(defs[n]["properties"].keys()) - {"type"} for n in names]
    common = set.intersection(*sets)
    order = list(defs[names[0]]["properties"].keys())
    return [key for key in order if key in common]


def emit_ts(schema: dict) -> str:
    defs = schema["$defs"]
    names = layer_defs(defs)
    base = compute_base_fields(defs, names)
    out = [HEADER_TS]

    out.append("export type HexColor = `#${string}`;\n")

    # Enums shared by many properties. Some live in `$defs`, others are written
    # inline on the layer properties, so each one is resolved from its source.
    inline_enums = {
        "AnimProperty": defs["Animation"]["properties"]["property"],
        "FitMode": defs["ImageLayer"]["properties"]["fit"],
        "Anchor": defs["RectLayer"]["properties"]["anchor"],
        "TrackMatte": defs["RectLayer"]["properties"]["track_matte"],
        "TextAlign": defs["TextLayer"]["properties"]["text_align"],
        "TextDirection": defs["TextLayer"]["properties"]["direction"],
    }
    for name in ("BlendMode", "FitMode", "Easing", "AnimProperty", "Anchor",
                 "TrackMatte", "TextAlign", "TextDirection", "TextAnimatorMode"):
        definition = defs.get(name)
        if definition is None:
            definition = inline_enums.get(name)
        if definition is None or not is_union_of_literals(definition):
            continue
        values = definition["enum"]
        # Short literal sets stay on one line; long ones wrap for readability.
        joined = literal_union(values)
        if len(values) <= 4:
            out.append(f"export type {name} = {joined};\n")
        else:
            out.append(f"export type {name} =\n  | " + "\n  | ".join(
                json.dumps(v) if isinstance(v, str) else str(v) for v in values
            ) + ";\n")

    stops = defs["LinearGradient"]["properties"]["stops"]["items"]
    out.append("export interface GradientStop {")
    for key, prop in stops["properties"].items():
        optional = "" if key in stops.get("required", []) else "?"
        out.append(f"  {key}{optional}: {ts_type(prop, 'LinearGradient', key)};")
    out.append("}\n")

    out.append("// Keyframe of a keyframed animation.\n")
    keyframe = defs["Animation"]["properties"]["keyframes"]["items"]
    out.append("export interface Keyframe {")
    for key, prop in keyframe["properties"].items():
        optional = "" if key in keyframe.get("required", []) else "?"
        doc = doc_line(prop)
        if doc:
            out.append(f"  /** {doc} */")
        out.append(f"  {key}{optional}: {ts_type(prop, 'Animation', key)};")
    out.append("}\n")

    # Hand-written dynamic text modes, because the schema leaves it open.
    out.append(
        "export type DynamicText =\n"
        '  | { mode: "typewriter"; text: string; start_sec?: number; end_sec?: number; cursor?: string }\n'
        '  | { mode: "counter"; from: number; to: number; decimals?: number; prefix?: string; '
        "suffix?: string; start_sec?: number; end_sec?: number; easing?: Easing }\n"
        '  | { mode: "timecode"; format?: "mm:ss" | "mm:ss.cc" | "hh:mm:ss"; offset_sec?: number };\n'
    )

    for name in ("LinearGradient", "Layout", "Shadow", "TextSpan", "SpringConfig",
                 "Echo", "TextAnimator", "WaveWarp", "Animation"):
        definition = defs[name]
        props = definition.get("properties", {})
        required = definition.get("required", [])
        doc = doc_line(definition)
        out.append(f"export interface {name} {{")
        for key, prop in props.items():
            optional = "" if key in required else "?"
            line_doc = doc_line(prop)
            if line_doc:
                out.append(f"  /** {line_doc} */")
            out.append(f"  {key}{optional}: {ts_type(prop, name, key)};")
        out.append("}\n")

    # Base layer: every field shared by all layer kinds.
    out.append("// Fields shared by every layer kind.\n")
    out.append("export interface BaseLayer {")
    rect_props = defs["RectLayer"]["properties"]
    for key in base:
        prop = rect_props[key]
        doc = doc_line(prop)
        if doc:
            out.append(f"  /** {doc} */")
        out.append(f"  {key}?: {ts_type(prop, 'RectLayer', key)};")
    out.append("}\n")

    for name in names:
        definition = defs[name]
        props = definition["properties"]
        required = definition.get("required", [])
        out.append(f"export interface {name} extends BaseLayer {{")
        for key, prop in props.items():
            if key in base:
                continue
            optional = "" if key in required else "?"
            doc = doc_line(prop)
            if doc:
                out.append(f"  /** {doc} */")
            out.append(f"  {key}{optional}: {ts_type(prop, name, key)};")
        out.append("}\n")

    include = defs["IncludeLayer"]
    out.append("export interface IncludeLayer {")
    for key, prop in include["properties"].items():
        optional = "" if key in include.get("required", []) else "?"
        out.append(f"  {key}{optional}: {ts_type(prop, 'IncludeLayer', key)};")
    out.append("}\n")

    out.append("export type Layer =")
    out.append("  | " + "\n  | ".join(names + ["IncludeLayer"]) + ";\n")

    canvas = schema["properties"]["canvas"]
    out.append("// Canvas and top-level scene fields.\n")
    out.append("export interface Canvas {")
    for key, prop in canvas["properties"].items():
        optional = "" if key in canvas.get("required", []) else "?"
        doc = doc_line(prop)
        if doc:
            out.append(f"  /** {doc} */")
        out.append(f"  {key}{optional}: {ts_type(prop, 'canvas', key)};")
    out.append("}\n")

    out.append("export interface CompositionProfile {")
    for key, prop in schema["properties"]["profiles"]["additionalProperties"]["properties"].items():
        optional = "" if key in () else "?"
        out.append(f"  {key}{optional}: {ts_type(prop, 'profile', key)};")
    out.append("}\n")

    audio = schema["properties"]["audio"]["items"]
    out.append("export interface AudioTrack {")
    for key, prop in audio["properties"].items():
        optional = "" if key in audio.get("required", []) else "?"
        doc = doc_line(prop)
        if doc:
            out.append(f"  /** {doc} */")
        out.append(f"  {key}{optional}: {ts_type(prop, 'audio', key)};")
    out.append("}\n")

    out.append("export interface RustrenScene {")
    for key, prop in schema["properties"].items():
        optional = "" if key in schema.get("required", []) else "?"
        doc = doc_line(prop)
        if doc:
            out.append(f"  /** {doc} */")
        out.append(f"  {key}{optional}: {ts_type(prop, 'scene', key)};")
    out.append("}\n")

    return "\n".join(out).rstrip() + "\n"


def emit_py(schema: dict) -> str:
    defs = schema["$defs"]
    names = layer_defs(defs)
    base = compute_base_fields(defs, names)
    out = [HEADER_PY]

    out.append("HexColor = str\n")
    for name in ("BlendMode", "FitMode", "Easing", "AnimProperty", "TextAnimatorMode"):
        definition = defs.get(name) or {
            "Easing": defs["Animation"]["properties"]["easing"],
            "FitMode": defs["ImageLayer"]["properties"]["fit"],
            "AnimProperty": defs["Animation"]["properties"]["property"],
        }.get(name)
        if definition and is_union_of_literals(definition):
            out.append(f"{name} = {py_str_literal(definition['enum'])}\n")
    out.append("Anchor = " + py_str_literal(defs["RectLayer"]["properties"]["anchor"]["enum"]) + "\n")
    out.append("TrackMatte = " + py_str_literal(defs["RectLayer"]["properties"]["track_matte"]["enum"]) + "\n")
    out.append("TextAlign = " + py_str_literal(defs["TextLayer"]["properties"]["text_align"]["enum"]) + "\n")
    out.append("TextDirection = " + py_str_literal(defs["TextLayer"]["properties"]["direction"]["enum"]) + "\n")

    out.append(
        'DynamicText = dict[str, Any]\n'
        '"""typewriter / counter / timecode options; see docs for each mode."""\n'
    )

    stops = defs["LinearGradient"]["properties"]["stops"]["items"]
    out.extend(
        typed_dict(
            "GradientStop",
            stops["properties"],
            "LinearGradient",
            "Gradient colour stop. Required: offset, color.",
        )
    )
    out.append("")

    keyframe = defs["Animation"]["properties"]["keyframes"]["items"]
    out.extend(
        typed_dict(
            "Keyframe",
            keyframe["properties"],
            "Animation",
            "Keyframe of a keyframed animation. Required: time, value.",
        )
    )
    out.append("")

    for name in ("LinearGradient", "Layout", "Shadow", "TextSpan", "SpringConfig", "Echo", "TextAnimator", "WaveWarp", "Animation"):
        definition = defs[name]
        required = definition.get("required", [])
        doc = doc_line(definition) or name
        req = f" Required: {', '.join(required)}." if required else ""
        out.extend(
            typed_dict(name, definition.get("properties", {}), name, f"{doc}.{req}")
        )
        out.append("")

    out.extend(
        typed_dict(
            "BaseLayer",
            {key: defs["RectLayer"]["properties"][key] for key in base},
            "RectLayer",
            "Fields shared by every layer kind.",
        )
    )
    out.append("")

    for name in names:
        definition = defs[name]
        required = [r for r in definition.get("required", []) if r != "type"]
        req = f" Required: {', '.join(required)}." if required else ""
        out.extend(
            typed_dict(
                name,
                definition["properties"],
                name,
                f"{name}.{req}",
                skip=set(base),
            )
        )
        out.append("")

    include = defs["IncludeLayer"]
    out.extend(
        typed_dict(
            "IncludeLayer",
            include["properties"],
            "IncludeLayer",
            "Reusable component. Required: src.",
        )
    )
    out.append("")

    out.append("Layer = Union[" + ", ".join(names + ["IncludeLayer"]) + "]\n")

    canvas = schema["properties"]["canvas"]
    out.extend(
        typed_dict(
            "Canvas",
            canvas["properties"],
            "canvas",
            "Required: width, height, fps, duration_secs.",
        )
    )
    out.append("")

    out.extend(
        typed_dict(
            "CompositionProfile",
            schema["properties"]["profiles"]["additionalProperties"]["properties"],
            "profile",
            "Per-composition canvas override.",
        )
    )
    out.append("")

    out.extend(
        typed_dict(
            "AudioTrack",
            schema["properties"]["audio"]["items"]["properties"],
            "audio",
            "Required: src.",
        )
    )
    out.append("")

    out.extend(
        typed_dict(
            "RustrenScene",
            schema["properties"],
            "scene",
            "Required: canvas, layers.",
        )
    )
    out.append("")

    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    schema = load_schema()
    ts = emit_ts(schema)
    py = emit_py(schema)

    if "--check" in argv:
        stale = []
        if TS_OUT.read_text() != ts:
            stale.append(str(TS_OUT.relative_to(ROOT)))
        if PY_OUT.read_text() != py:
            stale.append(str(PY_OUT.relative_to(ROOT)))
        if stale:
            print("stale SDK files: " + ", ".join(stale), file=sys.stderr)
            print("run: python3 scripts/gen_sdk.py", file=sys.stderr)
            return 1
        print("SDK files are up to date")
        return 0

    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text(ts)
    PY_OUT.write_text(py)
    print(f"wrote {TS_OUT.relative_to(ROOT)} and {PY_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
